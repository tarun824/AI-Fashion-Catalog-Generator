const tag = `[Integration:${PROVIDER_ID}]`;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const enc = encodeURIComponent;

/** product type schema cache: key -> {at, schema} */
const schemaCache = new Map();

const marketplaceOf = (c) => String(c?.marketplaceId || "").trim() || INDIA_MARKETPLACE_ID;
const productTypeOf = (c) => String(c?.productType || "").trim() || DEFAULT_PRODUCT_TYPE;

/** Re-type a generic 403 (httpClient says PII_ROLE_MISSING) when the call is not about PII. */
function asAccessDenied(err, what) {
  if (err instanceof ProviderError && err.type === "PII_ROLE_MISSING") {
    return new ProviderError(
      "CREDENTIALS_INVALID",
      `Amazon denied access to ${what}. Check that the app is authorized for this seller and has the required roles.`,
      { details: err.details, status: 403 },
    );
  }
  return err;
}

/** Collect Amazon "errors" array messages from a ProviderError body for VALIDATION details. */
function amazonMessages(err) {
  const errs = err?.details?.body?.errors;
  if (!Array.isArray(errs)) return [];
  return errs.map((e) => `${e.code || "Error"}: ${e.message || ""}`.trim());
}

function withAmazonDetail(err) {
  if (err instanceof ProviderError && err.type === "VALIDATION") {
    const msgs = amazonMessages(err);
    if (msgs.length) {
      return new ProviderError("VALIDATION", `Amazon rejected the request: ${msgs.join("; ")}`, {
        details: { ...(err.details || {}), amazonErrors: msgs },
        status: 400,
      });
    }
  }
  return err;
}

export class AmazonProvider extends BaseProvider {
  static id = PROVIDER_ID;
  static displayName = "Amazon India";
  static category = "marketplace";
  static description = "Import orders, publish listings, sync stock/price and send tracking to Amazon.in (SP-API).";
  static docsUrl = "https://developer-docs.amazon.com/sp-api";
  static features = ["Orders", "Listings", "Inventory", "Price", "Shipment confirmation"];
  static capabilities = {
    fetchOrders: true,
    publishProducts: true,
    updateInventory: true,
    updatePrice: true,
    confirmShipment: true,
  };

  credentialFields() {
    return [
      { key: "sellerId", label: "Seller ID (Merchant Token)", secret: false, required: true, help: "Seller Central > Settings > Account Info > Merchant Token" },
      { key: "lwaClientId", label: "LWA Client ID", secret: false, required: true, help: "Developer Central > your app > LWA credentials" },
      { key: "lwaClientSecret", label: "LWA Client Secret", secret: true, required: true },
      { key: "refreshToken", label: "Refresh Token", secret: true, required: true, help: "Generated by self-authorizing your private app in Developer Central" },
      { key: "marketplaceId", label: "Marketplace ID", secret: false, required: false, help: `Default ${INDIA_MARKETPLACE_ID} (Amazon.in)` },
      { key: "endpoint", label: "SP-API endpoint", secret: false, required: false, help: "Default https://sellingpartnerapi-eu.amazon.com" },
      { key: "productType", label: "Product type", secret: false, required: false, help: `Default ${DEFAULT_PRODUCT_TYPE}` },
      { key: "brand", label: "Brand name", secret: false, required: false, help: "Brand used on new listings" },
      { key: "useSandbox", label: "Use sandbox (true/false)", secret: false, required: false, help: "Sends calls to the SP-API sandbox host" },
    ];
  }

  /* ------------------------------ connection ------------------------------ */

  async testConnection(credentials, deps = {}) {
    try {
      await getAccessToken(credentials, { http: deps.tokenHttp });
    } catch (err) {
      if (err instanceof ProviderError) throw err;
      console.warn(`${tag} testConnection token step failed reason=${err.message}`);
      throw new ProviderError("UPSTREAM_ERROR", `Could not reach Amazon login service: ${err.message}`);
    }
    const sp = deps.sp || createSpClient(credentials, deps);
    let res;
    try {
      res = await sp.request({ method: "GET", url: "/sellers/v1/marketplaceParticipations" });
    } catch (err) {
      const e = asAccessDenied(err, "seller account info");
      console.warn(`${tag} testConnection marketplaceParticipations failed type=${e.type}`);
      throw e;
    }
    const list = Array.isArray(res.data?.payload) ? res.data.payload : [];
    const wanted = marketplaceOf(credentials);
    const match = list.find((p) => p?.marketplace?.id === wanted);
    if (!match) {
      console.warn(`${tag} testConnection marketplace ${wanted} not in participations count=${list.length}`);
      return {
        ok: false,
        message: `Credentials are valid but the seller account does not participate in marketplace ${wanted}. Check the Marketplace ID.`,
      };
    }
    const suspended = match.participation?.isParticipating === false;
    return {
      ok: !suspended,
      message: suspended
        ? `Connected, but the account is not currently participating in ${match.marketplace?.name || wanted}.`
        : `Connected to Amazon (${match.marketplace?.name || wanted}).`,
    };
  }

  /* ------------------------------- orders ------------------------------- */

  /**
   * @param {object} credentials
   * @param {{since?:Date, cursor?:string|null, limit?:number}} [params]
   */
  async fetchOrders(credentials, params = {}, deps = {}) {
    const sp = deps.sp || createSpClient(credentials, deps);
    const sleepFn = deps.sleep || sleep;
    const marketplaceId = marketplaceOf(credentials);
    const limit = Math.max(1, Math.min(Number(params.limit) || ORDERS_PAGE_SIZE, 500));
    const warnings = [];
    const state = { piiWarned: false };
    const warnOnce = (msg) => {
      if (!state.piiWarned) {
        state.piiWarned = true;
        warnings.push(msg);
      }
    };

    const maxSince = Date.now() - LAST_UPDATED_SAFETY_MS;
    const sinceMs = params.since instanceof Date ? params.since.getTime() : Date.now() - DEFAULT_LOOKBACK_DAYS * 86400000;
    const lastUpdatedAfter = new Date(Math.min(sinceMs, maxSince)).toISOString();

    const rawOrders = [];
    let nextToken = params.cursor || null;
    for (let page = 0; page < ORDERS_MAX_PAGES && rawOrders.length < limit; page++) {
      // TODO(verify): with NextToken, Amazon ignores the other filters; MarketplaceIds still sent.
      const query = nextToken
        ? { MarketplaceIds: marketplaceId, NextToken: nextToken }
        : {
            MarketplaceIds: marketplaceId,
            LastUpdatedAfter: lastUpdatedAfter,
            FulfillmentChannels: "MFN",
            MaxResultsPerPage: Math.min(limit, ORDERS_PAGE_SIZE),
          };
      let res;
      try {
        res = await sp.request({ method: "GET", url: "/orders/v0/orders", params: query });
      } catch (err) {
        const e = withAmazonDetail(asAccessDenied(err, "orders"));
        if (e.type === "RATE_LIMITED" && rawOrders.length) {
          console.warn(`${tag} fetchOrders rate limited after ${rawOrders.length} orders; returning partial`);
          warnings.push("Amazon rate limit hit; fetched a partial set. Run the fetch again in a minute.");
          break;
        }
        throw e;
      }
      const payload = res.data?.payload || {};
      rawOrders.push(...(payload.Orders || []));
      nextToken = payload.NextToken || null;
      if (!nextToken) break;
    }

    // Addresses: one RDT per chunk of orders (SELLER-fulfilled, not cancelled).
    const needAddress = rawOrders.filter((o) => o.FulfillmentChannel !== "AFN" && o.OrderStatus !== "Canceled");
    const addressById = await this._fetchAddresses(sp, needAddress.map((o) => o.AmazonOrderId), warnOnce, sleepFn);

    const orders = [];
    for (const raw of rawOrders) {
      const id = raw.AmazonOrderId;
      let items;
      try {
        items = await this._fetchAllItems(sp, id);
      } catch (err) {
        if (err.type === "RATE_LIMITED") {
          console.warn(`${tag} fetchOrders stopping orderItems for orderId=${id} reason=rate limited`);
          warnings.push("Amazon rate limit hit while reading order items; some orders were skipped. Fetch again shortly.");
          break;
        }
        console.warn(`${tag} skipped orderId=${id} reason=orderItems failed type=${err.type || "ERROR"} msg=${err.message}`);
        warnings.push(`Order ${id} skipped: could not read its items (${err.message}).`);
        continue;
      }
      if (!items.length) {
        console.warn(`${tag} skipped orderId=${id} reason=no items returned status=${raw.OrderStatus}`);
        warnings.push(`Order ${id} skipped: Amazon returned no items (status ${raw.OrderStatus}).`);
        continue;
      }
      orders.push(toNormalizedOrder(raw, items, addressById.get(id) || null));
    }

    return { orders, cursor: nextToken, warnings };
  }

  async _fetchAllItems(sp, orderId) {
    const items = [];
    let token = null;
    for (let i = 0; i < 20; i++) {
      const res = await sp.request({
        method: "GET",
        url: `/orders/v0/orders/${enc(orderId)}/orderItems`,
        params: token ? { NextToken: token } : {},
      });
      const p = res.data?.payload || {};
      items.push(...(p.OrderItems || []));
      token = p.NextToken || null;
      if (!token) break;
    }
    return items;
  }

  /**
   * Fetch ShippingAddress for each order via a Restricted Data Token.
   * Any 403/role failure degrades to "redacted" (never throws for PII).
   * @returns {Promise<Map<string, object>>} orderId -> ShippingAddress
   */
  async _fetchAddresses(sp, orderIds, warnOnce, sleepFn) {
    const out = new Map();
    for (let i = 0; i < orderIds.length; i += RDT_MAX_RESOURCES) {
      const chunk = orderIds.slice(i, i + RDT_MAX_RESOURCES);
      let rdt;
      try {
        rdt = await sp.getRestrictedDataToken(
          chunk.map((id) => ({ method: "GET", path: `/orders/v0/orders/${id}/address` })),
        );
      } catch (err) {
        if (err.type === "PII_ROLE_MISSING" || err.type === "CREDENTIALS_INVALID" || err.type === "VALIDATION") {
          console.warn(`${tag} RDT request failed type=${err.type} orders=${chunk.length} reason=PII role missing or not approved`);
          warnOnce(PII_WARNING);
          continue;
        }
        throw err;
      }
      let first = true;
      for (const id of chunk) {
        if (!first) await sleepFn(ADDRESS_MIN_INTERVAL_MS);
        first = false;
        try {
          const res = await sp.request(
            { method: "GET", url: `/orders/v0/orders/${enc(id)}/address` },
            { accessToken: rdt },
          );
          const addr = res.data?.payload?.ShippingAddress;
          if (addr) out.set(id, addr);
          else console.warn(`${tag} address empty orderId=${id} reason=no ShippingAddress in payload`);
        } catch (err) {
          if (err.type === "PII_ROLE_MISSING") {
            console.warn(`${tag} address denied orderId=${id} reason=403`);
            warnOnce(PII_WARNING);
          } else {
            console.warn(`${tag} address failed orderId=${id} type=${err.type || "ERROR"} reason=${err.message}`);
          }
        }
      }
    }
    return out;
  }

  /* ----------------------------- shipment ----------------------------- */

  async confirmShipment(credentials, order, shipment, deps = {}) {
    const sp = deps.sp || createSpClient(credentials, deps);
    const orderId = order?.marketplace?.externalOrderId;
    if (!orderId) {
      console.warn(`${tag} confirmShipment blocked orderId=${order?._id} reason=no externalOrderId`);
      throw new ProviderError("VALIDATION", "Order has no Amazon order id");
    }
    // Order.items does not persist OrderItemId, so read the live items from Amazon.
    let items;
    try {
      items = await this._fetchAllItems(sp, orderId);
    } catch (err) {
      throw withAmazonDetail(asAccessDenied(err, "order items"));
    }
    if (!items.length) {
      console.warn(`${tag} confirmShipment blocked externalOrderId=${orderId} reason=Amazon returned no items`);
      throw new ProviderError("VALIDATION", "Amazon returned no items for this order");
    }
    const shipDate = shipment.shipDate ? new Date(shipment.shipDate) : new Date();
    // Amazon rejects future ship dates.
    const safeShip = shipDate.getTime() > Date.now() ? new Date() : shipDate;
    const body = {
      marketplaceId: marketplaceOf(credentials),
      packageDetail: {
        packageReferenceId: 1,
        carrierCode: "Other",
        carrierName: shipment.carrierName,
        trackingNumber: shipment.awb,
        shipDate: safeShip.toISOString(),
        // TODO(verify): partially shipped items are not handled (ships the unshipped quantity)
        orderItems: items.map((it) => ({
          orderItemId: it.OrderItemId,
          quantity: Math.max(
            1,
            Number(it.QuantityOrdered || 0) - Number(it.QuantityShipped || 0),
          ),
        })),
      },
    };
    try {
      await sp.request({
        method: "POST",
        url: `/orders/v0/orders/${enc(orderId)}/shipmentConfirmation`,
        data: body,
      });
    } catch (err) {
      throw withAmazonDetail(asAccessDenied(err, "shipment confirmation"));
    }
    return { ok: true, message: "Tracking sent to Amazon" };
  }

  /* ------------------------------ listings ------------------------------ */

  async _getProductTypeSchema(sp, credentials, productType) {
    const marketplaceId = marketplaceOf(credentials);
    const key = `${marketplaceId}|${productType}`;
    const hit = schemaCache.get(key);
    if (hit && Date.now() - hit.at < SCHEMA_CACHE_TTL_MS) return hit.schema;
    try {
      const res = await sp.request({
        method: "GET",
        url: `/definitions/2020-09-01/productTypes/${enc(productType)}`,
        params: { marketplaceIds: marketplaceId, requirements: "LISTING", locale: LANGUAGE_TAG },
      });
      const link = res.data?.schema?.link?.resource;
      if (!link) {
        console.warn(`${tag} productType schema has no link productType=${productType}`);
        return null;
      }
      const schema = await (this._fetchSchemaJson || fetchPresignedJson)(link);
      schemaCache.set(key, { at: Date.now(), schema });
      return schema;
    } catch (err) {
      console.warn(`${tag} productType schema unavailable productType=${productType} type=${err.type || "ERROR"} reason=${err.message}; skipping pre-validation`);
      return null;
    }
  }

  async publishProduct(credentials, listing, opts = {}, deps = {}) {
    const dryRun = !!opts.dryRun;
    const sp = deps.sp || createSpClient(credentials, deps);
    const sellerId = String(credentials.sellerId || "").trim();
    if (!sellerId) {
      console.warn(`${tag} publish blocked sku=${listing?.sku} reason=sellerId missing`);
      throw new ProviderError("CREDENTIALS_INVALID", "Seller ID (Merchant Token) is not set");
    }
    const marketplaceId = marketplaceOf(credentials);
    const ctx = {
      marketplaceId,
      productType: productTypeOf(credentials),
      brand: String(credentials.brand || "").trim(),
      languageTag: LANGUAGE_TAG,
    };
    const mapped = toAmazonListing(listing, ctx);
    const issues = [];

    const schema = await this._getProductTypeSchema(sp, credentials, mapped.productType);
    let attributes = mapped.attributes;
    if (schema) {
      const { kept, dropped } = filterToSchema(schema, attributes);
      if (dropped.length) {
        console.warn(`${tag} dropping attributes not in schema sku=${listing.sku} productType=${mapped.productType} attrs=${dropped.join(",")}`);
      }
      attributes = kept;
      if (mapped.requirements === "LISTING") {
        const missing = findMissingRequired(schema, attributes);
        for (const m of missing) issues.push(`[ERROR] Missing required attribute: ${m}`);
      }
    }

    let res;
    try {
      res = await sp.request({
        method: "PUT",
        url: `/listings/2021-08-01/items/${enc(sellerId)}/${enc(listing.sku)}`,
        params: {
          marketplaceIds: marketplaceId,
          issueLocale: LANGUAGE_TAG,
          ...(dryRun ? { mode: "VALIDATION_PREVIEW" } : {}),
        },
        data: { productType: mapped.productType, requirements: mapped.requirements, attributes },
      });
    } catch (err) {
      throw withAmazonDetail(asAccessDenied(err, "listings"));
    }
    const out = mapListingResponse(res.data, { dryRun });
    const allIssues = [...issues, ...out.issues];
    // Local missing-required issues also make the result an error.
    const status = issues.length && out.status !== "error" ? "error" : out.status;
    return {
      externalId: res.data?.asin || listing.overrides?.asin || listing.sku,
      externalSku: listing.sku,
      status,
      issues: allIssues,
    };
  }

  async _patchListing(sp, credentials, sku, patches) {
    const sellerId = String(credentials.sellerId || "").trim();
    if (!sellerId) {
      console.warn(`${tag} patch blocked sku=${sku} reason=sellerId missing`);
      throw new ProviderError("CREDENTIALS_INVALID", "Seller ID (Merchant Token) is not set");
    }
    let res;
    try {
      res = await sp.request({
        method: "PATCH",
        url: `/listings/2021-08-01/items/${enc(sellerId)}/${enc(sku)}`,
        params: { marketplaceIds: marketplaceOf(credentials), issueLocale: LANGUAGE_TAG },
        data: { productType: productTypeOf(credentials), patches },
      });
    } catch (err) {
      throw withAmazonDetail(asAccessDenied(err, "listings"));
    }
    const rawIssues = res.data?.issues || [];
    const errors = rawIssues.filter((i) => i.severity === "ERROR").map((i) => i.message || i.code);
    const ok = res.data?.status !== "INVALID" && !errors.length;
    if (!ok) console.warn(`${tag} patch rejected sku=${sku} issues=${errors.length}`);
    return {
      ok,
      message: ok ? "Accepted by Amazon" : `Amazon rejected the update: ${errors.join("; ") || "INVALID"}`,
    };
  }

  async updateInventory(credentials, { externalSku, quantity }, deps = {}) {
    const sp = deps.sp || createSpClient(credentials, deps);
    return this._patchListing(sp, credentials, externalSku, [
      {
        op: "replace",
        path: "/attributes/fulfillment_availability",
        value: buildFulfillmentAvailability(quantity),
      },
    ]);
  }

  async updatePrice(credentials, { externalSku, mrp, sellingPrice }, deps = {}) {
    const sp = deps.sp || createSpClient(credentials, deps);
    const attrs = buildPriceAttributes(
      { mrp, sellingPrice, currency: "INR" },
      { marketplaceId: marketplaceOf(credentials) },
    );
    const patches = Object.entries(attrs).map(([k, v]) => ({
      op: "replace",
      path: `/attributes/${k}`,
      value: v,
    }));
    if (!patches.length) {
      console.warn(`${tag} updatePrice blocked sku=${externalSku} reason=no mrp/sellingPrice`);
      throw new ProviderError("VALIDATION", "Provide a selling price and/or MRP");
    }
    return this._patchListing(sp, credentials, externalSku, patches);
  }
}

export function _clearSchemaCache() {
  schemaCache.clear();
}

export default new AmazonProvider();
